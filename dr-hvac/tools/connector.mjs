/* Writes src/dr/14_dr_connector_raw.js from src/connector/drhvac-connector.php: the plugin's source as one string, the way
   the dashboard carries the FORGE bridge (FORGE_BRIDGE_PHP), so Dr. HVAC can hand it over as a zip to upload.
   `node tools/connector.mjs` after any change to the plugin; tests/wp.test.mjs fails when the two drift apart. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export function rawScript(php) {
  /* JSON string escaping, plus the one sequence that must never sit inside an inline script */
  const LS = String.fromCharCode(0x2028), PS = String.fromCharCode(0x2029);
  const lit = JSON.stringify(php).replace(/<\/script/gi, '<\\/script').split(LS).join('\\u2028').split(PS).join('\\u2029');
  return `/* ==== src/dr/14_dr_connector_raw.js ==== */\n/* ==== dr_connector_raw ==== */\n/* Generated by tools/connector.mjs from src/connector/drhvac-connector.php. Do not edit. */\nconst DRHVAC_CONNECTOR_PHP=${lit};\nglobalThis.DRHVAC_CONNECTOR_PHP = DRHVAC_CONNECTOR_PHP;\n`;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const php = fs.readFileSync(path.join(HERE, 'src/connector/drhvac-connector.php'), 'utf8');
  fs.writeFileSync(path.join(HERE, 'src/dr/14_dr_connector_raw.js'), rawScript(php));
  console.log(`src/dr/14_dr_connector_raw.js  ${(php.length / 1024).toFixed(1)} KB of PHP`);
}
