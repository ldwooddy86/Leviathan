// Build the DFW Thermal Debt Atlas from the app/ source tree and atlas.template.html.
//
//   node build.mjs                 write app/atlas.html (the browser app page: external scripts, bundled fonts)
//                                  and dist/DFW_Thermal_Debt_Atlas.html (the single file edition: everything inline)
//   node build.mjs --release       also write DFW_Thermal_Debt_Atlas.html beside this file and the install zip
//                                  ../DFW-Thermal-Debt-Atlas-browser-app.zip (unzip, then Load unpacked)
//   node build.mjs --check         validate only (exit 1 on any problem), write nothing
//   node build.mjs --verify <file> prove the single file edition rebuilds <file> byte for byte (used once, on the
//                                  Build 4 file the tree was unpacked from; see tools/unpack.mjs)
//
// The template is the page skeleton. Three kinds of line are special:
//   <!--@css path-->      the stylesheet: inline <style> in the single file, <link> in the browser app
//   <!--@js path-->       a classic script: inline <script> in the single file, <script src> in the browser app
//   <!--@single-->…       the rest of the line belongs to the single file edition only
//   <!--@ext-->…          the rest of the line belongs to the browser app page only
// No packages: Node 22.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { deflateRawSync, crc32 } from 'node:zlib';
import { dirname, join, resolve, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = dirname(fileURLToPath(import.meta.url));
export const APP = join(ROOT, 'app');
const DIRECTIVE = /^<!--@(css|js) ([^ ]+)-->$/;
const ONLY = /^<!--@(single|ext)-->(.*)$/;
const sha = s => createHash('sha256').update(s).digest('hex');
const template = () => readFileSync(join(ROOT, 'atlas.template.html'), 'utf8').split('\n');

/* The template's sections for one edition, in order: [{ kind: 'css' | 'js', path }] */
export function sections(edition) {
  return template().map(l => { const o = ONLY.exec(l); if (o) { if (edition && o[1] !== edition) return null; l = o[2]; } return DIRECTIVE.exec(l); }).filter(Boolean).map(m => ({ kind: m[1], path: m[2] }));
}
export function render(edition) {
  return template().flatMap(l => {
    const o = ONLY.exec(l); if (o) { if (o[1] !== edition) return []; l = o[2]; }
    const m = DIRECTIVE.exec(l); if (!m) return [l];
    if (edition === 'ext') return [m[1] === 'css' ? `<link rel="stylesheet" href="${m[2]}">` : `<script src="${m[2]}"></script>`];
    const body = readFileSync(join(APP, m[2]), 'utf8');
    if (m[1] === 'js' && /<\/script/i.test(body)) throw new Error(`${m[2]} holds a literal </script; write it <\\/script so the single file edition stays whole`);
    if (m[1] === 'css' && /<\/style/i.test(body)) throw new Error(`${m[2]} holds a literal </style`);
    return [m[1] === 'css' ? `<style>\n${body}</style>` : `<script>\n${body}</script>`];
  }).join('\n');
}
export const buildSingle = () => render('single');
export const buildExtPage = () => render('ext');

/* ---------- registry: what the popup, the address bar and the worker can open ---------- */
/* Read from the module scripts and the data file themselves, so it cannot drift from the page. */
export function registry() {
  const mods = [];
  for (const s of sections('ext').filter(s => s.kind === 'js' && s.path.startsWith('js/'))) {
    const body = readFileSync(join(APP, s.path), 'utf8');
    for (const m of body.matchAll(/registerModule\(\{\s*key:\s*'([^']+)',\s*num:\s*'([^']+)',\s*title:\s*'((?:[^'\\]|\\.)*)',\s*desc:\s*'((?:[^'\\]|\\.)*)'/g)) mods.push({ key: m[1], num: m[2], title: m[3].replace(/\\(.)/g, '$1'), desc: m[4].replace(/\\(.)/g, '$1') });
  }
  const raw = readFileSync(join(APP, 'data', 'atlas-data.js'), 'utf8');
  const D = JSON.parse(raw.slice(raw.indexOf('{'), raw.lastIndexOf('}') + 1));
  const zi = D.zcols.indexOf('zip'), ci = D.zcols.indexOf('city'), ki = D.zcols.indexOf('ci');
  const zips = D.zrows.map(r => [r[zi], r[ci], r[ki] != null && D.counties[r[ki]] ? D.counties[r[ki]].name : '']).sort((a, b) => a[0].localeCompare(b[0]));
  const man = JSON.parse(readFileSync(join(APP, 'manifest.json'), 'utf8'));
  return { version: man.version, compiled: D.meta.compiled, modules: mods, zips };
}
export const registryScript = () => `/* Generated by build.mjs from the module scripts and the data file. Do not edit. */\nglobalThis.TDA_REGISTRY = ${JSON.stringify(registry())};\n`;

/* ---------- the live layer lists inside background.js and popup.html ---------- */
export const liveList = () => sections('ext').filter(s => s.kind === 'js' && s.path.startsWith('live/') && s.path !== 'live/page.js').map(s => s.path);
/* [{ file, now, want }]: each file as it is and as it should be */
export function liveSync() {
  const list = liveList(), out = [];
  const bg = join(APP, 'background.js');
  if (existsSync(bg)) { const now = readFileSync(bg, 'utf8'); out.push({ file: 'app/background.js', path: bg, now, want: now.replace(/importScripts\([^)]*\);( \/\* live layer:)/, `importScripts(${list.map(p => `'${p}'`).join(', ')});$1`) }); }
  const pop = join(APP, 'popup.html');
  if (existsSync(pop)) { const now = readFileSync(pop, 'utf8'); out.push({ file: 'app/popup.html', path: pop, now, want: now.replace(/<!--live-->[\s\S]*?<!--\/live-->/, `<!--live-->${list.map(p => `<script src="${p}"></script>`).join('')}<!--/live-->`) }); }
  return out;
}

/* ---------- validation ---------- */
export function validate() {
  const problems = []; const bad = m => problems.push(m);
  const tpl = template().join('\n');
  for (const ed of ['single', 'ext']) for (const s of sections(ed)) if (!existsSync(join(APP, s.path))) bad(`template names ${s.path}, which does not exist`);
  const manifestPath = join(APP, 'manifest.json');
  if (existsSync(manifestPath)) {
    let man; try { man = JSON.parse(readFileSync(manifestPath, 'utf8')); } catch (e) { bad('manifest.json is not JSON: ' + e.message); }
    if (man) {
      if (man.manifest_version !== 3) bad('manifest_version must be 3');
      for (const p of [man.background && man.background.service_worker, man.action && man.action.default_popup, ...Object.values(man.icons || {})].filter(Boolean)) if (!existsSync(join(APP, p))) bad(`manifest names ${p}, which does not exist`);
      const csp = man.content_security_policy && man.content_security_policy.extension_pages;
      if (csp && /unsafe-inline|unsafe-eval/.test(csp.split(';').find(d => /script-src/.test(d)) || '')) bad('the extension page policy must not allow inline or eval script');
      /* the build number shown in the page must match the manifest version's major number */
      const m = /Build (\d+)/.exec(tpl); if (m && String(man.version).split('.')[0] !== m[1]) bad(`the template says Build ${m[1]} but the manifest version is ${man.version}`);
    }
    /* the worker and the popup must load exactly the live layer the page loads (page.js is the page's own glue) */
    for (const f of liveSync()) if (f.now !== f.want) bad(`${f.file} loads a different live layer than the template (run "node build.mjs" to bring it in step)`);
  }
  /* extension pages cannot run inline script: the generated page must carry none, and no script may build inline handlers */
  const page = buildExtPage();
  if (/<script(?![^>]*\bsrc=)[^>]*>/i.test(page)) bad('the browser app page would carry an inline <script>');
  for (const s of sections('ext').filter(s => s.kind === 'js')) {
    if (!existsSync(join(APP, s.path))) continue; const body = readFileSync(join(APP, s.path), 'utf8');
    if (/\bnew Function\s*\(|[^.\w]eval\s*\(/.test(body)) bad(`${s.path} uses eval or new Function, which the browser app page forbids`);
  }
  return problems;
}

/* ---------- zip (deflate, no packages) ---------- */
export function zip(files) {                                   // files: [{ name, data: Buffer }]
  const parts = [], central = []; let offset = 0;
  const d = new Date(), dosTime = ((d.getHours() << 11) | (d.getMinutes() << 5) | (d.getSeconds() >> 1)) & 0xFFFF, dosDate = (((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate()) & 0xFFFF;
  for (const f of files) {
    const name = Buffer.from(f.name, 'utf8'), raw = f.data, def = deflateRawSync(raw, { level: 9 }), stored = def.length >= raw.length, body = stored ? raw : def, crc = crc32(raw) >>> 0;
    const lh = Buffer.alloc(30); lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(20, 4); lh.writeUInt16LE(0x0800, 6); lh.writeUInt16LE(stored ? 0 : 8, 8); lh.writeUInt16LE(dosTime, 10); lh.writeUInt16LE(dosDate, 12); lh.writeUInt32LE(crc, 14); lh.writeUInt32LE(body.length, 18); lh.writeUInt32LE(raw.length, 22); lh.writeUInt16LE(name.length, 26);
    parts.push(lh, name, body);
    const ch = Buffer.alloc(46); ch.writeUInt32LE(0x02014b50, 0); ch.writeUInt16LE(20, 4); ch.writeUInt16LE(20, 6); ch.writeUInt16LE(0x0800, 8); ch.writeUInt16LE(stored ? 0 : 8, 10); ch.writeUInt16LE(dosTime, 12); ch.writeUInt16LE(dosDate, 14); ch.writeUInt32LE(crc, 16); ch.writeUInt32LE(body.length, 20); ch.writeUInt32LE(raw.length, 24); ch.writeUInt16LE(name.length, 28); ch.writeUInt32LE(offset, 42);
    central.push(ch, name); offset += 30 + name.length + body.length;
  }
  const cd = Buffer.concat(central), end = Buffer.alloc(22); end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(files.length, 8); end.writeUInt16LE(files.length, 10); end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...parts, cd, end]);
}
export function appFiles() {
  const out = []; const walk = dir => { for (const n of readdirSync(dir).sort()) { const p = join(dir, n); if (statSync(p).isDirectory()) walk(p); else if (!/(^|\/)\.|\.map$|~$/.test(n)) out.push(p); } };
  walk(APP); return out.map(p => ({ rel: relative(APP, p).split(sep).join('/'), abs: p }));
}

/* ---------- command line ---------- */
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const a = process.argv.slice(2), has = k => a.includes(k);
  const v = a.indexOf('--verify');
  if (v >= 0) {
    const want = readFileSync(a[v + 1], 'utf8'), got = buildSingle();
    if (want === got) console.log(`byte for byte: ${sha(got)} (${got.length} chars)`);
    else { console.error(`MISMATCH: built ${sha(got)} (${got.length}) vs file ${sha(want)} (${want.length})`); process.exit(1); }
  } else {
    if (!has('--check')) for (const f of liveSync()) if (f.now !== f.want) { writeFileSync(f.path, f.want); console.log(`${f.file}: live layer list brought in step with the template`); }
    const problems = validate();
    if (problems.length) { console.error('build check failed:\n  ' + problems.join('\n  ')); process.exit(1); }
    if (has('--check')) { console.log(`check passed: ${sections('single').length} sections in the single file, ${sections('ext').length} in the browser app page`); process.exit(0); }
    const single = buildSingle(), page = buildExtPage();
    writeFileSync(join(APP, 'atlas.html'), page);
    if (existsSync(join(APP, 'manifest.json'))) writeFileSync(join(APP, 'registry.js'), registryScript());
    const di = a.indexOf('--dist'), dist = di >= 0 ? resolve(a[di + 1]) : join(ROOT, 'dist');      // --dist <dir>: write the single file somewhere else
    mkdirSync(dist, { recursive: true });
    writeFileSync(join(dist, 'DFW_Thermal_Debt_Atlas.html'), single);
    console.log(`app/atlas.html                      ${String(page.length).padStart(9)} chars  (${sections('ext').length} sections, external)`);
    console.log(`${relative(ROOT, join(dist, 'DFW_Thermal_Debt_Atlas.html')).padEnd(35)} ${String(single.length).padStart(9)} chars  sha256 ${sha(single).slice(0, 16)}`);
    if (has('--release')) {
      writeFileSync(join(ROOT, 'DFW_Thermal_Debt_Atlas.html'), single);
      const folder = 'dfw-thermal-debt-atlas/';
      const files = appFiles().map(f => ({ name: folder + f.rel, data: readFileSync(f.abs) }));
      const z = zip(files), zp = resolve(ROOT, '..', 'DFW-Thermal-Debt-Atlas-browser-app.zip');
      writeFileSync(zp, z);
      console.log(`DFW_Thermal_Debt_Atlas.html         ${String(single.length).padStart(9)} chars  (the single file edition, for the repository)`);
      console.log(`../DFW-Thermal-Debt-Atlas-browser-app.zip ${(z.length / 1048576).toFixed(2)} MB, ${files.length} files under ${folder}`);
    }
  }
}
