/* Outis build: regenerates the files derived from lib/, checks the extension, and writes the install zip.
     node tools/build.mjs            regenerate rules/*.json, inject/opt/*.js, inject/places/*.js and shield.js's suffix list
     node tools/build.mjs --check    verify those are current and every manifest reference exists; writes nothing
     node tools/build.mjs --zip [f]  also write the zip (default ../Outis-chrome-extension.zip): unzip, Load unpacked
   No packages needed. */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { trackerRules, paramRules } from '../lib/trackers.js';
import { PLACES, placePayload } from '../lib/places.js';
import { FLAGS } from '../lib/settings.js';
import { MULTI_SUFFIXES } from '../lib/sites.js';
import { malwareRules } from '../lib/malware.js';
import { COMMAND_PATTERNS, DANGEROUS_SCHEMES, OFFICE_SCHEMES, MICROSOFT_HOSTS } from '../lib/safety.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const CHECK = args.includes('--check');
const ZIP = args.includes('--zip');
const zipArg = (() => { const i = args.indexOf('--zip'); const v = args[i + 1]; return i >= 0 && v && !v.startsWith('--') ? v : null; })();
const ZIP_ROOT = 'outis';

const problems = [];
const wrote = [];
const rel = f => path.relative(ROOT, f).split(path.sep).join('/');

/* ---- generated files ---- */
function expected() {
  const out = new Map();
  out.set('rules/trackers.json', JSON.stringify(trackerRules(), null, 1) + '\n');
  out.set('rules/params.json', JSON.stringify(paramRules()) + '\n');
  out.set('rules/malware.json', JSON.stringify(malwareRules(), null, 1) + '\n');
  for (const f of FLAGS) {
    out.set(`inject/opt/${f}.js`, `/* Generated by tools/build.mjs from lib/settings.js (FLAGS). */\n(globalThis.__outis_cfg || (globalThis.__outis_cfg = {}))[${JSON.stringify(f)}] = 1;\n`);
  }
  for (const p of PLACES) {
    out.set(`inject/places/${p.id}.js`, `/* Generated by tools/build.mjs from lib/places.js. */\n(globalThis.__outis_cfg || (globalThis.__outis_cfg = {})).place = ${JSON.stringify(placePayload(p))};\n`);
  }
  const shieldPath = 'inject/shield.js';
  const shield = fs.readFileSync(path.join(ROOT, shieldPath), 'utf8');
  const re = /\/\*@suffixes\*\/const SUFFIXES = '[^']*';\/\*@end\*\//;
  if (!re.test(shield)) problems.push('inject/shield.js: the /*@suffixes*/ ... /*@end*/ line is missing');
  let next = shield.replace(re, `/*@suffixes*/const SUFFIXES = '${MULTI_SUFFIXES.join(' ')}';/*@end*/`);
  /* the safety patterns, from lib/safety.js */
  const sre = /\/\*@safety\*\/const SAFETY = [^\n]*;\/\*@end\*\//;
  const safety = { commands: COMMAND_PATTERNS, schemes: DANGEROUS_SCHEMES, office: OFFICE_SCHEMES, microsoft: MICROSOFT_HOSTS };
  if (!sre.test(next)) problems.push('inject/shield.js: the /*@safety*/ ... /*@end*/ line is missing');
  else next = next.replace(sre, () => `/*@safety*/const SAFETY = ${JSON.stringify(safety)};/*@end*/`);
  if (re.test(shield)) out.set(shieldPath, next);
  return out;
}

function sync() {
  const want = expected();
  for (const [file, content] of want) {
    const abs = path.join(ROOT, file);
    const have = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (have === content) continue;
    if (CHECK) { problems.push(`${file} is out of date: run node tools/build.mjs`); continue; }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
    wrote.push(file);
  }
  /* stale generated files */
  for (const dir of ['inject/opt', 'inject/places']) {
    for (const f of fs.readdirSync(path.join(ROOT, dir))) {
      const file = `${dir}/${f}`;
      if (want.has(file)) continue;
      if (CHECK) problems.push(`${file} is not generated from lib/ any more: run node tools/build.mjs`);
      else { fs.unlinkSync(path.join(ROOT, file)); wrote.push(file + ' (removed)'); }
    }
  }
}

/* ---- checks ---- */
function validate() {
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'manifest.json'), 'utf8'));
  const refs = [manifest.background.service_worker, manifest.action.default_popup, manifest.options_page,
    ...Object.values(manifest.icons), ...Object.values(manifest.action.default_icon),
    ...manifest.declarative_net_request.rule_resources.map(r => r.path)];
  for (const r of refs) if (!fs.existsSync(path.join(ROOT, r))) problems.push(`manifest.json references a missing file: ${r}`);
  for (const w of manifest.web_accessible_resources) {
    for (const r of w.resources) {
      const dir = path.join(ROOT, path.dirname(r));
      const base = path.basename(r);
      const ok = base.includes('*') ? fs.existsSync(dir) && fs.readdirSync(dir).some(f => new RegExp('^' + base.replace(/[.]/g, '\\.').replace(/\*/g, '.*') + '$').test(f)) : fs.existsSync(path.join(ROOT, r));
      if (!ok) problems.push(`web_accessible_resources names a missing file: ${r}`);
    }
  }
  for (const r of trackerRules()) {
    const p = r.action.redirect && r.action.redirect.extensionPath;
    if (p && !fs.existsSync(path.join(ROOT, p))) problems.push(`rules/trackers.json redirects to a missing file: ${p}`);
  }
  const js = [];
  const walk = d => { for (const e of fs.readdirSync(path.join(ROOT, d), { withFileTypes: true })) { const r = d ? `${d}/${e.name}` : e.name; if (/^(node_modules|_metadata|tests\/e2e\/out)/.test(r)) continue; if (e.isDirectory()) walk(r); else if (/\.(m?js)$/.test(e.name)) js.push(r); } };
  walk('');
  for (const f of js) {
    const r = spawnSync(process.execPath, ['--check', path.join(ROOT, f)], { encoding: 'utf8' });
    if (r.status !== 0) problems.push(`node --check ${f}: ${(r.stderr || '').trim().split('\n').slice(0, 4).join(' ')}`);
  }
  return js.length;
}

/* ---- zip ---- */
const CRC = (() => { const t = new Uint32Array(256); for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; } return t; })();
const crc32 = b => { let c = 0xFFFFFFFF; for (let i = 0; i < b.length; i++) c = CRC[(c ^ b[i]) & 0xFF] ^ (c >>> 8); return (c ^ 0xFFFFFFFF) >>> 0; };
function writeZip(entries) {
  const now = new Date();
  const time = ((now.getHours() << 11) | (now.getMinutes() << 5) | (now.getSeconds() >> 1)) & 0xFFFF;
  const date = (((now.getFullYear() - 1980) << 9) | ((now.getMonth() + 1) << 5) | now.getDate()) & 0xFFFF;
  const parts = [], central = [];
  let offset = 0;
  for (const { name, data } of entries) {
    const n = Buffer.from(name, 'utf8'), crc = crc32(data);
    let method = 0, body = data;
    const z = zlib.deflateRawSync(data, { level: 9 });
    if (z.length < data.length) { method = 8; body = z; }
    const lh = Buffer.alloc(30);
    lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(20, 4); lh.writeUInt16LE(0x0800, 6); lh.writeUInt16LE(method, 8);
    lh.writeUInt16LE(time, 10); lh.writeUInt16LE(date, 12); lh.writeUInt32LE(crc, 14); lh.writeUInt32LE(body.length, 18);
    lh.writeUInt32LE(data.length, 22); lh.writeUInt16LE(n.length, 26); lh.writeUInt16LE(0, 28);
    parts.push(lh, n, body);
    const ch = Buffer.alloc(46);
    ch.writeUInt32LE(0x02014b50, 0); ch.writeUInt16LE(20, 4); ch.writeUInt16LE(20, 6); ch.writeUInt16LE(0x0800, 8);
    ch.writeUInt16LE(method, 10); ch.writeUInt16LE(time, 12); ch.writeUInt16LE(date, 14); ch.writeUInt32LE(crc, 16);
    ch.writeUInt32LE(body.length, 20); ch.writeUInt32LE(data.length, 24); ch.writeUInt16LE(n.length, 28);
    ch.writeUInt32LE(offset, 42);
    central.push(ch, n);
    offset += 30 + n.length + body.length;
  }
  const cd = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(entries.length, 8); end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...parts, cd, end]);
}
/* What ships: everything the browser loads, nothing for building or testing. */
export function shippedFiles() {
  /* _metadata/ is what Chrome writes into an unpacked extension's folder when it loads it (compiled rule indexes). */
  const skip = r => /^(tests|tools|node_modules|_metadata)(\/|$)/.test(r) || /^package(-lock)?\.json$/.test(r) || /(^|\/)(\.DS_Store|Thumbs\.db|\.git.*|.*\.swp|.*~)$/.test(r);
  const out = [];
  const walk = d => {
    for (const e of fs.readdirSync(path.join(ROOT, d), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const r = d ? `${d}/${e.name}` : e.name;
      if (skip(r)) continue;
      if (e.isDirectory()) walk(r); else if (e.isFile()) out.push(r);
    }
  };
  walk('');
  return out;
}
function zip() {
  const files = shippedFiles();
  const entries = files.map(f => ({ name: `${ZIP_ROOT}/${f}`, data: fs.readFileSync(path.join(ROOT, f)) }));
  const buf = writeZip(entries);
  const out = path.resolve(zipArg || path.join(ROOT, '..', 'Outis-chrome-extension.zip'));
  fs.writeFileSync(out, buf);
  console.log(`zip: ${entries.length} files under ${ZIP_ROOT}/, ${(buf.length / 1024).toFixed(1)} KB -> ${out}`);
}

if (path.resolve(process.argv[1] || '') === fileURLToPath(import.meta.url)) {
  sync();
  const n = validate();
  if (wrote.length) console.log('wrote\n  ' + wrote.join('\n  '));
  if (problems.length) { console.log('PROBLEMS\n  ' + problems.join('\n  ')); process.exit(1); }
  console.log(`${CHECK ? 'checked' : 'built'}: ${PLACES.length} places, ${FLAGS.length} flags, ${trackerRules().length} tracker rules, ${paramRules().length} link rules, ${malwareRules().length} malware rules, ${n} scripts pass node --check`);
  if (ZIP) zip();
}
