# The gazetteer of California's physical geography for the Scout tab.
# Names and coordinates: USGS Geographic Names Information System, Domestic Names, California text file
#   (https://prd-tnm.s3.amazonaws.com/StagedProducts/GeographicNames/DomesticNames/DomesticNames_CA_Text.zip, fetched 2026-11-19).
# Heights (tiers 1 and 2): USGS 3DEP elevation service read at the GNIS point (sample_3dep.py); a sharp summit can read a
#   few metres under its surveyed height. Tier 3 carries no height: the page reads it from the terrain tiles when asked.
# Tiers: 1 = shown from the statewide view, 2 = from region zoom, 3 = from local zoom (every other GNIS range, every GNIS
#   gap, and the highest GNIS summit in each 0.15 degree cell by the statewide grid).
# A valley's GNIS point is its mouth; where GNIS also gives its head, the label sits half way between the two.
# Output: topo_gaz.js (window.__SCOUT_TOPO_GAZ__ = { k: kinds, f: [[name, kind index, tier, lat*1e4, lon*1e4, metres or null], ...] }).
# python3 -I build_gaz.py
import csv, json, math, os, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'dl/gnis/x/Text/DomesticNames_CA.txt')
KINDS = ['range', 'peak', 'pass', 'desert', 'valley', 'water', 'island']
found = json.load(open(os.path.join(HERE, 'work/gaz_found.json')))
ele = json.load(open(os.path.join(HERE, 'work/elev_3dep.json'))) if os.path.exists(os.path.join(HERE, 'work/elev_3dep.json')) else {}
SKIP = {'Sierra Nevada', 'Coast Ranges', 'Transverse Ranges', 'Mojave Desert', 'Central Valley', 'Channel Islands'}   # drawn from the province outlines, or their GNIS point sits at one end
# the two ends of the state, at the heights SP/research/ca/sources_scout_live.md (section 4a, "Known height") carries
KNOWN = {('Mount Whitney', 'Tulare'): 4421, ('Badwater Basin', 'Inyo'): -85.5}
out, ids = [], set()
for f in found['found']:
    if f['n'] in SKIP: continue
    la, lo = f['lat'], f['lon']
    if f['k'] in ('valley', 'desert') and f.get('slat') and f.get('slon') and f['cls'] == 'Valley':
        la, lo = (la + f['slat']) / 2, (lo + f['slon']) / 2
    e = ele.get(f['id']) if f['k'] in ('peak', 'pass', 'water') or f['n'] in ('Badwater Basin', 'Death Valley') else None
    if (f['n'], f['county']) in KNOWN: e = KNOWN[(f['n'], f['county'])]
    out.append([f['n'], KINDS.index(f['k']), f['t'], round(la * 1e4), round(lo * 1e4), None if e is None else round(e)]); ids.add(f['id'])
n12 = len(out)
# tier 3
m = json.load(open(os.path.join(HERE, 'work/grid_meta.json'))); G = np.load(os.path.join(HERE, 'work/grid_ele.npy')); M = np.load(os.path.join(HERE, 'work/grid_mask.npy'))
def gpx(la, lo):
    x = (lo + 180) / 360 * 256 * 2 ** m['z'] - m['x0']; s = math.sin(math.radians(la)); y = (0.5 - math.log((1 + s) / (1 - s)) / (4 * math.pi)) * 256 * 2 ** m['z'] - m['y0']
    return int(x), int(y)
cells = {}; nr = ng = 0
with open(SRC, encoding='utf-8-sig') as fh:
    for r in csv.DictReader(fh, delimiter='|'):
        if r['state_name'] != 'California' or r['feature_id'] in ids: continue
        try: la, lo = float(r['prim_lat_dec']), float(r['prim_long_dec'])
        except ValueError: continue
        if not la or not lo: continue
        c = r['feature_class']
        if c == 'Range': out.append([r['feature_name'], 0, 3, round(la * 1e4), round(lo * 1e4), None]); nr += 1
        elif c == 'Gap': out.append([r['feature_name'], 2, 3, round(la * 1e4), round(lo * 1e4), None]); ng += 1
        elif c == 'Summit':
            x, y = gpx(la, lo)
            if not (0 <= x < m['w'] and 0 <= y < m['h']) or not M[y, x]: continue
            k = (int(la / 0.15), int(lo / 0.15)); h = float(G[y, x])
            if k not in cells or h > cells[k][0]: cells[k] = (h, [r['feature_name'], 1, 3, round(la * 1e4), round(lo * 1e4), None])
out += [v[1] for v in cells.values()]
print('tiers 1 and 2:', n12, '(with a height:', sum(1 for o in out[:n12] if o[5] is not None), '); tier 3: ranges', nr, 'gaps', ng, 'summits', len(cells))
missing = [mm[1] for mm in found['missing']]
js = '/* Generated by build_gaz.py. Names and coordinates: USGS GNIS Domestic Names (California). Heights in metres: USGS 3DEP at the GNIS point. */\n'
js += 'window.__SCOUT_TOPO_GAZ__ = ' + json.dumps(dict(k=KINDS, f=out, missing=missing, src='USGS Geographic Names Information System (GNIS), Domestic Names, California; heights from USGS 3DEP at the GNIS point'), separators=(',', ':'), ensure_ascii=False) + ';\n'
open(os.path.join(HERE, 'topo_gaz.js'), 'w', encoding='utf-8').write(js)
print('wrote topo_gaz.js', len(js.encode()), 'bytes; not in GNIS under these names:', ', '.join(missing))
