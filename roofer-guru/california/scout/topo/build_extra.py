# The two small tables behind the terrain block's roofing readings.
# 1. Title 24 building climate zone by ZIP code: California Energy Commission, "Building Climate Zones by ZIP Code"
#    (https://www.energy.ca.gov/sites/default/files/2020-04/BuildingClimateZonesByZIPCode_ada.xlsx, fetched 2026-11-19;
#    the Energy Code defines the 16 zones by ZIP code, Reference Joint Appendix JA2). Packed per zone as ZIP - 90000 in
#    three base 36 digits.
# 2. ASCE 7-22 ground snow load, Risk Category II, and the elevation the snow model used: the 0.05 degree grid the
#    hazard research sampled from gis.asce.org (CA/dl/hazard/asce7/ASCE722_grid_0p05deg.csv; sources_weather_hazard.md
#    section 8c: read as lb/ft2, a unit the service does not state). One byte a cell: round(sqrt(psf) * 8), 0 = no
#    value; elevation as round(metres / 18) + 1, 0 = no value.
# Output: topo_extra_data.js (window.__SCOUT_TOPO_XD__).  python3 -I build_extra.py
import base64, csv, json, math, os, re, zipfile
HERE = os.path.dirname(os.path.abspath(__file__))
z = zipfile.ZipFile(os.path.join(HERE, 'dl/cec/zip.xlsx')); sh = z.read('xl/worksheets/sheet1.xml').decode()
cz = {}
for row in re.findall(r'<row[^>]*>(.*?)</row>', sh, re.S)[1:]:
    c = re.findall(r'<c r="([A-Z]+)\d+"[^>]*>(?:<v>(.*?)</v>)?', row)
    d = dict(c)
    try: zp, zn = int(float(d['A'])), int(float(d['B']))
    except (KeyError, ValueError): continue
    if 90000 <= zp <= 96999 and 1 <= zn <= 16: cz.setdefault(zn, []).append(zp)
B36 = '0123456789abcdefghijklmnopqrstuvwxyz'
def b36(n): return B36[n // 1296] + B36[n // 36 % 36] + B36[n % 36]
czp = {str(k): ''.join(b36(v - 90000) for v in sorted(vs)) for k, vs in sorted(cz.items())}
print('climate zones:', sum(len(v) for v in cz.values()), 'ZIP codes;', {k: len(v) for k, v in sorted(cz.items())})

LAT0, LON0, D = 32.5, -124.5, 0.05
rows = list(csv.DictReader(open(os.path.join(HERE, '../../dl/hazard/asce7/ASCE722_grid_0p05deg.csv'))))
W = int(round((max(float(r['lon']) for r in rows) - LON0) / D)) + 1; H = int(round((max(float(r['lat']) for r in rows) - LAT0) / D)) + 1
sn = bytearray(W * H); el = bytearray(W * H); n = 0; mx = 0
for r in rows:
    i = int(round((float(r['lon']) - LON0) / D)); j = int(round((float(r['lat']) - LAT0) / D))
    try: v = float(r['s2022_RiskCategory2'])
    except ValueError: continue
    if not (0 <= v < 1100): continue
    sn[j * W + i] = max(1, min(255, int(round(math.sqrt(v) * 8)))); n += 1; mx = max(mx, v)
    try:
        e = float(r['s2022_Elevation'])
        if -200 < e < 4500: el[j * W + i] = max(1, min(255, int(round(e / 18)) + 1))
    except ValueError: pass
print('snow grid', W, 'x', H, 'cells with a value', n, 'largest', mx)
out = dict(cz=czp, czSrc='California Energy Commission, Building Climate Zones by ZIP Code (Energy Code Reference Joint Appendix JA2)',
           snow=dict(lat0=LAT0, lon0=LON0, d=D, w=W, h=H, psf=base64.b64encode(bytes(sn)).decode(), el=base64.b64encode(bytes(el)).decode()),
           snowSrc='ASCE 7-22 ground snow load, Risk Category II, sampled from the ASCE hazard services on a 0.05 degree grid')
js = '/* Generated by build_extra.py. Title 24 climate zone by ZIP (California Energy Commission) and the ASCE 7-22 ground snow load grid (0.05 degree). */\n'
js += 'window.__SCOUT_TOPO_XD__ = ' + json.dumps(out, separators=(',', ':')) + ';\n'
open(os.path.join(HERE, 'topo_extra_data.js'), 'w').write(js); print('wrote topo_extra_data.js', len(js), 'bytes')
